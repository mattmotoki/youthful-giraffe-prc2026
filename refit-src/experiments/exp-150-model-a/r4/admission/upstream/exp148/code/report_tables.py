"""exp-148: the REPORT tables, generated from the score, clock-loss, stacker and ranking JSON
files (never typed by hand).

    python report_tables.py --stack DIR --score score-main.json --month score-month.json \
        --clockloss clockloss-main.json [--rank ranking-<form>.json] --out report-tables.md

The candidate form is the SPEC-r1 item 1 choice: the form (LightGBM `S`, CatBoost `Scat`, their
mean `Sb`) with the lowest `cv_pooled` MSE averaged over the five outer owners of the full-input
stacker. G is in s² per row (base minus candidate, W = N_cell / 344,841), positive = the
candidate is better; intervals are the frozen airport-day resampling (95 %). Write-once.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

CV_FORM = {"mse_lgb": "S", "mse_cat": "Scat", "mse_mean": "Sb"}
S22_OF = {"S": "S22", "Scat": "S22cat", "Sb": "S22b"}


def sha(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def fmt(x, nd=1):
    return "–" if x is None else f"{x:,.{nd}f}"


def form_choice(stack: Path) -> tuple[str, list[str]]:
    rows, sums = [], {k: 0.0 for k in ("mse_anchor", *CV_FORM)}
    for k in range(1, 6):
        r = json.loads((stack / f"S-outer-{k}.json").read_text())
        cv = r["cv_pooled"]
        for c in sums:
            sums[c] += cv[c] / 5
        rows.append(f"| {k} | {r['train_rows']:,} | {r['rounds']} | {r['rounds_cat']} | "
                    + " | ".join(fmt(cv[c], 0) for c in ("mse_anchor", *CV_FORM)) + " |")
    best = min(CV_FORM, key=lambda c: sums[c])
    out = ["| owner | training rows | LightGBM rounds | CatBoost rounds | MSE anchor | MSE S (LightGBM) | "
           "MSE Scat (CatBoost) | MSE Sb (mean) |", "|---|---|---|---|---|---|---|---|", *rows,
           "| **mean** | | | | " + " | ".join(("**" + fmt(sums[c], 0) + "**") for c in ("mse_anchor", *CV_FORM)) + " |",
           "", f"Chosen form: **{CV_FORM[best]}** (lowest mean pooled inner MSE, {fmt(sums[best], 0)} s²)."]
    return CV_FORM[best], out


def g_row(name: str, e: dict) -> str:
    a, c = e["all"], e["clean"]
    iv = a.get("interval") or {}
    return (f"| {name} | {fmt(a['G'])} | [{fmt(iv.get('lo95'))}, {fmt(iv.get('hi95'))}] | "
            f"{fmt(iv.get('p_G_le_0'), 3)} | {fmt(c['G'])} | {fmt(a.get('G_without_top_days'))} | "
            f"{fmt(a.get('gain_s'), 2)} |")


G_HEAD = ["| comparison (candidate vs base) | G all rows | 95 % interval | P(G ≤ 0) | G clean | "
          "G without top 5 days | gain (s) |", "|---|---|---|---|---|---|---|"]


def g_table(scores: dict, form: str) -> list[str]:
    s22 = S22_OF[form]
    order = [(f"{form}_vs_v32_ref", f"{form} vs v32 saved route (reference)"),
             (f"{form}_vs_v22_ref", f"{form} vs v22 saved route (reference)"),
             (f"{form}_vs_anchor", f"{form} vs anchor"),
             (f"{form}_vs_{s22}", f"{form} vs v22-input stacker {s22}"),
             (f"{s22}_vs_anchor", f"{s22} vs anchor"),
             ("v32_ref_vs_anchor", "v32 saved route vs anchor"),
             ("v22_ref_vs_anchor", "v22 saved route vs anchor"),
             ("v32_ref_vs_v22_ref", "v32 saved route vs v22 saved route")]
    others = [f for f in ("S", "Scat", "Sb") if f != form]
    order += [(f"{f}_vs_{b}", f"(other form) {f} vs {b}") for f in others
              for b in ("v32_ref", "anchor", S22_OF[f])]
    return G_HEAD + [g_row(label, scores[key]) for key, label in order if key in scores]


def views(scores: dict, key: str) -> list[str]:
    a = scores[key]["all"]
    out = [f"View of `{key}` (all rows; G contributions in s² per row, they sum to G):", ""]
    for v, d in a["views"].items():
        out.append(f"- {v}: " + "; ".join(f"{k} {fmt(x)}" for k, x in d.items()))
    out.append("- top airport-days: " + "; ".join(
        f"{t['airport']} {t['month']:02d}-{t['day']:02d} {fmt(t['contribution'])}" for t in a["top_airport_days"]))
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stack", type=Path, required=True)
    ap.add_argument("--score", type=Path, required=True)
    ap.add_argument("--month", type=Path)
    ap.add_argument("--clockloss", type=Path)
    ap.add_argument("--rank", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    if a.out.exists():
        raise SystemExit(f"{a.out} exists; write-once")
    form, lines = form_choice(a.stack)
    sc = json.loads(a.score.read_text())
    md = ["# exp-148 report tables (generated by code/report_tables.py)", "",
          "Inputs: " + ", ".join(f"`{p.name}` {sha(p)[:12]}…" for p in (a.score, a.month, a.clockloss, a.rank) if p),
          "", "## Form choice (SPEC-r1 item 1, inner predictions only)", "", *lines, "",
          f"## Week-pair G, five outer pairs joined ({sc['rows']:,} rows)", "", *g_table(sc["scores"], form), "",
          "RMSE by stage (s): " + "; ".join(f"{k} {fmt(v, 2)}" for k, v in sc["rmse_by_stage"].items()), "",
          *views(sc["scores"], f"{form}_vs_v32_ref"), "", *views(sc["scores"], f"{form}_vs_anchor"), ""]
    if a.month:
        mo = json.loads(a.month.read_text())
        md += [f"## Whole-month check (SPEC-r1 item 3; janjul fits, owners m01/m07; {mo['rows']:,} rows)", "",
               *g_table(mo["scores"], form), ""]
    if a.clockloss:
        cl = json.loads(a.clockloss.read_text())
        md += ["## Clock-loss view (VALIDATION §9; ADS-B-derived inputs blanked on dark airport-days)", "",
               "Parity (masked re-prediction machinery re-predicts the saved outer predictions): "
               + "; ".join(f"{k} {v if not isinstance(v, float) else f'{v:.2e}'}" for k, v in cl["parity"].items()), ""]
        for scheme in cl["masks"]:
            rows = [g_row(f"{scheme}: {k.split(':', 1)[1]}", v) for k, v in cl["scores"].items()
                    if k.startswith(scheme + ":") and k.split(":", 1)[1].split("_vs_")[0] in (form, S22_OF[form])]
            md += G_HEAD + rows + [""]
    if a.rank:
        rk = json.loads(a.rank.read_text())
        md += ["## Ranking vector", "",
               f"`{rk['what']}`: {rk['rows']:,} rows, min {fmt(rk['min'])} s, mean {fmt(rk['mean'])} s, "
               f"max {fmt(rk['max'])} s; {rk['rows_from_v32']:,} rows keep v32 (unsupported cells "
               f"{rk['unsupported_rows_by_cell']}); against v32: {rk['vs_v32']}; sha256 `{rk['output_sha256']}`.", ""]
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
