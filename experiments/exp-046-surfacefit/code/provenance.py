"""exp-046-surfacefit step 4: the archive digest table `docs/EXTERNAL-DATA.md` cites.

The eligibility rule's documentation condition needs every consumed archive named with
the digest its publisher signed and the digest computed on the bytes actually read.  The
harvest and the pilot record both in their own per-day run files, so this script reads
those and writes `docs/external-data-archives.md`.  Re-run it whenever the harvest lands
another month; it is a projection of the record, never a second copy of it.

    .venv/bin/python experiments/exp-046-surfacefit/code/provenance.py
"""
from __future__ import annotations

import datetime as dt
import json
from pathlib import Path

EXP = Path(__file__).resolve().parents[1]
ROOT = EXP.parents[1]
OUT = ROOT / "docs/external-data-archives.md"
SOURCES = [
    ("exp-043-pilot", ROOT / "experiments/exp-043-pilot/analysis", "run_*.json"),
    ("exp-045-harvest", ROOT / "experiments/exp-045-harvest/analysis/runs", "run_*.json"),
]


def rows() -> list[dict]:
    out = []
    for exp, d, pat in SOURCES:
        for p in sorted(d.glob(pat)):
            r = json.loads(p.read_text())
            day = r.get("day") or p.stem.replace("run_", "")
            for a in r.get("digest_match", []):
                out.append({"exp": exp, "day": day,
                            "repo": r.get("repo", "adsblol/globe_history_2025"),
                            "tag": r.get("tag", ""), "asset": a["name"],
                            "bytes": a.get("bytes"), "published": a.get("published"),
                            "computed": a.get("computed"), "ok": a.get("ok"),
                            # a run record that carries no retrieval field falls back to
                            # its own modification time, which is not durable evidence --
                            # so it is labelled as such rather than printed as a fact
                            # (round 2 FALLBACK, non-blocking)
                            "retrieved": (r.get("retrieved") or r.get("written")
                                          or r.get("fetched_utc")
                                          or (dt.datetime.fromtimestamp(
                                              p.stat().st_mtime,
                                              dt.timezone.utc).strftime("%Y-%m-%d")
                                              + " (record mtime)")),
                            "record": str(p.relative_to(ROOT))})
    return out


def main() -> None:
    rs = rows()
    days = sorted({r["day"] for r in rs})
    ok = sum(1 for r in rs if r["ok"])
    tot_bytes = sum(r["bytes"] or 0 for r in rs)
    lines = [
        "# External data: the archives consumed, and their digests",
        "",
        "Generated by `experiments/exp-046-surfacefit/code/provenance.py` from the",
        "per-day run records of `exp-043-pilot` and `exp-045-harvest`. It is the digest",
        "appendix `docs/EXTERNAL-DATA.md` §2 cites, and it is a projection of those",
        "records: correct a digest there, not here.",
        "",
        f"**{len(days)} archive days, {len(rs)} split assets, "
        f"{tot_bytes / 1e9:.1f} GB read, {ok} of {len(rs)} digests matching the "
        "publisher's.**",
        "",
        "`published` is the SHA-256 GitHub publishes for the release asset, recorded",
        "before a byte was fetched. `computed` is the SHA-256 of the bytes the filter",
        "actually consumed. An asset the publisher listed but that has no row here is a",
        "stream that ended before the asset did; those are listed in the second table.",
        "The pilot's first two days are the only such assets on the record and",
        "`exp-043-pilot/RESULTS.md` §1 states the cause",
        "(the tar's end-of-archive marker stopped the reader before the last bytes of the",
        "second part; the member accounting shows the archive was read whole, and the",
        "kernel was fixed to drain the stream, which is why every later day certifies",
        "both parts).",
        "",
        "Digests are printed WHOLE, not as a prefix: a reader who refetches an asset must",
        "be able to compare the sixty-four characters they compute against the ones here",
        "(Sol round 1, Standards). `retrieved` is the UTC day the bytes were read where the",
        "run record carries one; where it does not, it is the record file's own",
        "modification time and says so, which is weaker evidence and is marked.",
        "",
        "| day | retrieved | repo | asset | GB | publisher SHA-256 | computed SHA-256 | "
        "match | record |",
        "| --- | --- | --- | --- | ---: | --- | --- | --- | --- |",
    ]
    for r in rs:
        gb = (r["bytes"] or 0) / 1e9
        lines.append(
            f"| {r['day']} | {r['retrieved']} | `{r['repo']}` | `{r['asset']}` | "
            f"{gb:.2f} | `{r['published'] or ''}` | `{r['computed'] or ''}` | "
            f"{'yes' if r['ok'] else 'NO'} | `{r['record']}` |")
    lines += ["", "## Published assets with no verified digest", "",
              "| day | asset | GB published | record | cause |",
              "| --- | --- | ---: | --- | --- |"]
    missing = []
    for _exp, d, pat in SOURCES:
        for p in sorted(d.glob(pat)):
            r = json.loads(p.read_text())
            done = {a["name"] for a in r.get("digest_match", [])}
            for a in r.get("assets_published", []):
                if a["name"] in done:
                    continue
                missing.append(
                    f"| {r.get('day', p.stem)} | `{a['name']}` | "
                    f"{(a.get('size') or 0) / 1e9:.2f} | `{p.relative_to(ROOT)}` | "
                    "the tar end-of-archive marker stopped the reader before the last "
                    "bytes; member accounting shows the archive was read whole "
                    "(exp-043-pilot/RESULTS.md §1) |")
    lines += missing or ["| — | — | — | — | none |"]
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"{OUT}: {len(days)} days, {len(rs)} assets, {ok} digests verified")


if __name__ == "__main__":
    main()
