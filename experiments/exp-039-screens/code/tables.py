def ci(v, nd=2):
    return f"[{v[0]:+.{nd}f}, {v[1]:+.{nd}f}]"


def tbl(rows, head):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


