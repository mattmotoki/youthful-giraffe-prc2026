BEGIN = "<!-- TABLES:q0{k} -->"
END = "<!-- /TABLES -->"


def inject(k: int) -> None:
    """Replace the marked block in Q0k.md with the generated tables."""
    rep = EXP / f"Q0{k}.md"
    if not rep.exists():
        return
    txt = rep.read_text()
    b, e = BEGIN.format(k=k), END
    if b not in txt or e not in txt:
        print(f"  no markers in {rep.name}; skipped")
        return
    head, rest = txt.split(b, 1)
    _, tail = rest.split(e, 1)
    rep.write_text(head + b + "\n" + (A / f"tables-q0{k}.md").read_text() + e + tail)
    print(f"  injected: {rep}")


def main() -> None:
    for k, fn in ((3, q03), (4, q04), (5, q05), (6, q06)):
        p = A / f"tables-q0{k}.md"
        p.write_text(fn())
        print(f"  written: {p}")
        inject(k)
    import packet as PK
    print(f"  written: {PK.rows_manifest()}")


if __name__ == "__main__":
    main()
