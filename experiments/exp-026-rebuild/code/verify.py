"""The gate a candidate must pass BEFORE it enters `submissions/candidates/`.

Review round 2 found the round-1 fix incomplete: `finalise.py` moved the work
file into place unconditionally whenever no config matched the stage name, which
is exactly stack-5's case, so the one candidate queued for upload reached the
upload directory with `cross_checked: false`.  The rule now has no hole in it --

    a candidate this module cannot verify independently is not published.

Two verifiers, one per kind of candidate, plus the structural checks every
candidate takes:

`blend`   the vector is rebuilt through `prc.blend.build_candidate`, the lane's
          own end-to-end path, from the config that declares `_stage_name`.
          `rebuild_blend.py` and `build_candidate` are two implementations of
          one rule, so this catches a divergence between them.

`stack-5` the vector is rebuilt by `serve_stack5.build`, the same callable that
          produced it -- so this is a reproduction check, not an independent
          reimplementation, and it is labelled as one.  What carries the weight
          for stack-5 is the STRUCTURE: 344,453 of its rows are the stacker's,
          but its anchor is blend-5, and blend-5 IS verified independently
          (`build_candidate`) and against the shipped `youthful-giraffe_v2`
          object.  So the checks below pin stack-5 to that anchor on the 388
          `noac` rows, pin the guard invariant on all 344,841, and pin the shape
          to the template.  A stale, corrupt, truncated, mis-ordered or
          wrong-variant file fails; a bug inside `build` itself would not, and
          that is what `tests/serve_check.py` and the review are for.

Every check raises `Failed` with the measured number.  Nothing here prints a
warning and continues.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import frames as F  # noqa: E402
import regime_table as RT  # noqa: E402
# The repository root goes at the END: `code/` must stay ahead of it so
# a module at the root cannot shadow one of this experiment's own
# (round 4 -- a root-level `verify.py` would have replaced the gate).
sys.path.append(str(F.ROOT))
import prc.blend as B  # noqa: E402
import prc.data as D  # noqa: E402

CONFIGS = F.EXP / "configs"
#: Values must agree to the last bit the writer can carry.  Both paths do the
#: same arithmetic in the same process, so anything above float noise is a bug.
TOL = 1e-9


#: The rebuilt blend-5 and the uploaded v2 bytes agree to 1.455e-10 s
#: (RESULTS section 6a): the same arithmetic summed in a different order.
#: Exact equality is the right test against the local rebuild and the
#: wrong one against separately generated bytes.
V2_TOL = 1e-9


class Failed(RuntimeError):
    """A candidate failed verification. It is not published."""


def close(a: np.ndarray, b: np.ndarray, tol: float, what: str) -> float:
    """Max |a - b|, refusing anything that is not demonstrably within `tol`.

    Round 4 found the same defect in three places: the comparisons were written
    `if diff > TOL: raise`, and `diff` is NaN whenever either side holds a NaN
    or a reindex missed a row -- and `NaN > TOL` is **False**, so the check
    PASSED on exactly the inputs it existed to catch. Every comparison now goes
    through here, which requires both sides finite and asks the question the
    other way round: publish only if `d <= tol` is true.
    """
    a = np.asarray(a, "float64"); b = np.asarray(b, "float64")
    if a.shape != b.shape:
        raise Failed(f"{what}: shapes {a.shape} against {b.shape}")
    for lab, v in (("left", a), ("right", b)):
        if not np.isfinite(v).all():
            raise Failed(f"{what}: {int((~np.isfinite(v)).sum())} non-finite values "
                         f"on the {lab}, so no comparison can be trusted")
    d = float(np.abs(a - b).max()) if a.size else 0.0
    if not (d <= tol):
        raise Failed(f"{what}: differs by {d:.6g} s, over the {tol:g} s tolerance")
    return d


def _values(path: Path) -> pd.Series:
    d = pd.read_parquet(path)
    col = D.TARGET if D.TARGET in d.columns else "y_pred"
    return pd.Series(d[col].to_numpy("float64"),
                     index=d["MVT_ID_mvt"].to_numpy("float64"))


def stored_dtypes(path: Path) -> dict:
    """The dtypes as STORED, read from the parquet schema.

    Round 3: `structural` used to check the dtype of an array `_values` had
    already cast to float64, so a stored float32 column passed a float64 gate.
    The schema is the only place the question can be honestly asked.
    """
    import pyarrow.parquet as pq
    s = pq.ParquetFile(path).schema_arrow
    return {n: str(s.field(n).type) for n in s.names}


def structural(path: Path, rec: dict) -> None:
    """Shape checks every candidate takes, against the live template."""
    d = pd.read_parquet(path)
    T = D.load_submitting()
    if list(d.columns) != ["MVT_ID_mvt", D.TARGET]:
        raise Failed(f"columns are {list(d.columns)}")
    dt = stored_dtypes(path)
    rec["stored_dtypes"] = dt
    if dt.get(D.TARGET) != "double" or dt.get("MVT_ID_mvt") != "double":
        raise Failed(f"stored dtypes are {dt}, expected double for both")
    y = d[D.TARGET].to_numpy("float64")
    if len(d) != len(T):
        raise Failed(f"{len(d)} rows against the template's {len(T)}")
    if not np.array_equal(d["MVT_ID_mvt"].to_numpy("float64"),
                          T["MVT_ID_mvt"].to_numpy("float64")):
        raise Failed("id order is not the template's")
    if not np.isfinite(y).all():
        raise Failed(f"{int((~np.isfinite(y)).sum())} non-finite values")
    if (y < B.FLOOR - 1e-9).any():
        raise Failed(f"{int((y < B.FLOOR - 1e-9).sum())} values under the floor")
    rec.update(n=int(len(d)), min=float(y.min()), median=float(np.median(y)),
               p99=float(np.quantile(y, 0.99)), max=float(y.max()))


def guard_invariant(path: Path, gates: pd.DataFrame, rec: dict) -> None:
    """The served residual must lie inside the bounds the guard clips to.

    This proves the guard's EFFECT on the published file, which is the property
    that matters; round 2 noted that asserting the call happened would not.
    """
    d = pd.read_parquet(path)
    g = gates.set_index("MVT_ID_mvt").reindex(d["MVT_ID_mvt"].to_numpy("float64"))
    a = g["d_takeoff_aobt"].to_numpy("float64")
    ok = np.isfinite(a)
    r = a[ok] - d[D.TARGET].to_numpy("float64")[ok]
    lo, hi = F.GUARD
    if not ((r >= lo - 1e-6) & (r <= hi + 1e-6)).all():
        raise Failed(f"implied residual outside the guard bounds: "
                     f"[{r.min():.1f}, {r.max():.1f}] against [{lo}, {hi}]")
    rec["residual_range"] = [float(r.min()), float(r.max())]


def verify_blend(name: str, path: Path, cfg_path: Path, rec: dict) -> None:
    tmp = path.with_suffix(".verify.parquet")
    try:
        B.build_candidate(json.loads(cfg_path.read_text()), tmp, root=F.ROOT)
        a, b = _values(path), _values(tmp)
        if not a.index.equals(b.index):
            raise Failed("build_candidate returned a different id set")
        diff = close(a.to_numpy(), b.to_numpy(), TOL,
                     f"{name} against prc.blend.build_candidate")
        rec.update(verifier="prc.blend.build_candidate", independent=True,
                   max_abs_diff=diff, config=cfg_path.name)
    finally:
        tmp.unlink(missing_ok=True)


def verify_stack5(path: Path, gates: pd.DataFrame, rec: dict, variant: str) -> None:
    import serve_stack5 as SS
    b = SS.build(gates, variant)
    got = _values(path)
    want = pd.Series(b["pred"], index=b["ids"]).reindex(got.index)
    if want.isna().any():
        raise Failed("the rebuild does not cover every id in the file")
    diff = float(np.abs(got.to_numpy() - want.to_numpy()).max())
    rec.update(verifier="serve_stack5.build", independent=False,
               max_abs_diff=diff, variant=variant)
    if diff > TOL:
        raise Failed(f"differs from a fresh serve_stack5.build by {diff:.6g} s")

    # The anchor is the part of stack-5 that IS independently verified: it is
    # blend-5, which build_candidate rebuilds and which matches the shipped
    # youthful-giraffe_v2 object.  Pin the noac rows to it.
    anchor = pd.Series(b["anchor"], index=b["ids"])
    anchor = np.maximum(anchor.reindex(got.index).to_numpy(), B.FLOOR)
    anchor = B.apply_residual_guard(
        anchor, gates.set_index("MVT_ID_mvt").reindex(got.index)
        ["d_takeoff_aobt"].to_numpy("float64"), *F.GUARD, B.FLOOR)
    reg = gates.set_index("MVT_ID_mvt").reindex(got.index)["regime"].to_numpy()
    noac = reg == "noac"
    rec["n_noac"] = int(noac.sum())
    if variant == "keep-noac":
        if rec["n_noac"] != 388:
            raise Failed(f"{rec['n_noac']} noac rows, expected 388")
        off = float(np.abs(got.to_numpy()[noac] - anchor[noac]).max())
        rec["noac_vs_anchor_max_abs_diff"] = off
        if off > TOL:
            raise Failed(f"keep-noac: noac rows differ from the anchor by {off:.6g} s")
        moved = int((got.to_numpy()[~noac] != anchor[~noac]).sum())
        rec["non_noac_rows_moved"] = moved
        if moved < 300_000:
            raise Failed(f"only {moved} non-noac rows differ from the anchor; "
                         f"this looks like the anchor, not a stacker")

    # stack-5's only INDEPENDENT anchor is blend-5, so blend-5 must be present
    # AND must itself pass its own independent verifier. Round 3: this was
    # `if blend5.exists()`, so an absent blend-5 skipped the check entirely and a
    # present one had its bytes trusted without being verified.
    blend5 = F.ROOT / "submissions/candidates/exp-026-blend-5.parquet"
    if not blend5.exists():
        raise Failed(
            f"{blend5.relative_to(F.ROOT)} is absent. stack-5's anchor is blend-5 and "
            f"blend-5 is the only part of stack-5 that can be verified independently, "
            f"so stack-5 is not publishable without it. Finalise blend-5 first.")
    b5cfg = next((q for q in sorted(CONFIGS.glob("*.json"))
                  if json.loads(q.read_text()).get("_stage_name") == "blend-5"), None)
    if b5cfg is None:
        raise Failed("no config declares _stage_name 'blend-5', so the anchor "
                     "reference cannot be independently verified")
    b5rec: dict = {}
    verify_blend("blend-5", blend5, b5cfg, b5rec)          # raises if blend-5 is wrong
    rec["anchor_reference_verified"] = {"file": str(blend5.relative_to(F.ROOT)),
                                        "max_abs_diff": b5rec["max_abs_diff"]}
    b5v = _values(blend5)
    if not b5v.index.equals(got.index):
        raise Failed("the verified blend-5 does not carry stack-5's id set")
    rec["anchor_vs_verified_blend5_max_abs_diff"] = close(
        anchor, b5v.to_numpy(), TOL, "stack-5's serve-time anchor against verified blend-5")


#: The published object the noac candidates are defined against. Round 4:
#: verifying only against the LOCAL blend-5 rebuild proves the candidate matches
#: whatever this checkout currently builds, not what was uploaded -- a coherently
#: changed base and member set would pass. v2 is immutable published bytes and is
#: pinned by hash, so the claim "identical to v2 off the noac rows" is now checked
#: against v2 itself.
UPLOADED_V2 = "submissions/uploaded/youthful-giraffe_v2.parquet"
V2_SHA = "5d6a99610907bc432e2e46fb9ea11fc8103feb8aa9efdd3f7c86f1188866a4cb"
#: Each noac source pinned by content, so the "matches the committed source"
#: claim cannot be satisfied by a source that changed under it.
SOURCE_SHA = {
    "exp002": "f35fa267e7607ad1375fdf1b286574aa282ea2c4a7720efd78ded89c2679c730",
    "drop-tailv4": "c47deeb1ea88ce7f44555ab7c17adb7e2422b7c8d966f3d93b83aa8b9f689f00",
    "drop-v3": "4d4f9f9e751b2a1d5f935ad39450130b0a47b2e128cd01a7d543fdc8c2e0c039",
}


def _pinned(rel: str, want: str, what: str) -> Path:
    q = F.ROOT / rel
    if not q.exists():
        raise Failed(f"{what}: {rel} is absent")
    got = D.sha256(q)
    if got != want:
        raise Failed(f"{what}: {rel} hashes {got[:12]}, not the pinned {want[:12]}")
    return q


def verify_noac_swap(path: Path, gates: pd.DataFrame, rec: dict, variant: str) -> None:
    """A `noac-<source>` candidate: blend-5 everywhere, a substitute on 388 rows.

    The defining property is what the board reading rests on, so it is checked
    against things this checkout cannot silently change:

      * the non-`noac` rows must equal **uploaded v2**, pinned by hash, at 0.0
        exact against the local blend-5 rebuild and within 1e-9 against v2's own
        bytes (the two differ by float summation noise of order 1e-10, RESULTS
        section 6a);
      * the `noac` row set must be **exactly the source's id set**, not merely
        388 rows carrying a `noac` label -- round 4 noted that a gate table with
        one label swapped would keep the count and free an arbitrary row;
      * the `noac` values must equal the **pinned** source file.

    Every comparison goes through `close`, which fails on NaN rather than
    passing on it.
    """
    import noac_swap as NS
    source = rec["name"].split("noac-", 1)[1]
    if source not in NS.SOURCES or source not in SOURCE_SHA:
        raise Failed(f"unknown noac source {source!r}")
    got = _values(path)

    # ---- the base: the local rebuild, verified, AND the uploaded bytes -------
    blend5 = F.ROOT / "submissions/candidates/exp-026-blend-5.parquet"
    if not blend5.exists():
        raise Failed(f"{blend5.relative_to(F.ROOT)} is absent; this candidate is "
                     f"defined as blend-5 off the noac rows and cannot be checked")
    b5cfg = next((q for q in sorted(CONFIGS.glob("*.json"))
                  if json.loads(q.read_text()).get("_stage_name") == "blend-5"), None)
    if b5cfg is None:
        raise Failed("no config declares _stage_name 'blend-5'")
    b5rec: dict = {}
    verify_blend("blend-5", blend5, b5cfg, b5rec)      # the base, independently
    base = _values(blend5)
    v2 = _values(_pinned(UPLOADED_V2, V2_SHA, "the uploaded base"))
    for lab, s in (("blend-5", base), ("uploaded v2", v2)):
        if not s.index.equals(got.index):
            raise Failed(f"{lab} does not carry this candidate's id set")

    # ---- the row set comes from a PINNED artifact, not from a label count ----
    # exp-002's file is the canonical 388-row noac set and is pinned by hash, so
    # it defines the rows for every variant -- including the two whose source is
    # a full 344,841-row candidate and therefore says nothing about which rows
    # are noac. The mutable gate cache is then required to AGREE with it, which
    # is what makes a swapped label an error instead of a free row.
    ids_path = _pinned(NS.SOURCES["exp002"], SOURCE_SHA["exp002"], "the noac row set")
    noac_ids = _values(ids_path).index
    if noac_ids.has_duplicates or len(noac_ids) != 388:
        raise Failed(f"the pinned noac row set has {len(noac_ids)} rows, expected 388")
    reg = gates.set_index("MVT_ID_mvt").reindex(got.index)["regime"].to_numpy()
    gate_noac = set(got.index.to_numpy()[reg == "noac"].tolist())
    want = set(noac_ids.to_numpy().tolist())
    if gate_noac != want:
        raise Failed(f"the gate table's noac labels disagree with the pinned row set: "
                     f"{len(gate_noac - want)} extra, {len(want - gate_noac)} missing")
    noac = np.isin(got.index.to_numpy(), noac_ids.to_numpy())
    rec["n_noac"] = int(noac.sum())
    if rec["n_noac"] != 388:
        raise Failed(f"{rec['n_noac']} noac rows, expected 388")

    src_path = _pinned(NS.SOURCES[source], SOURCE_SHA[source], f"the {source} source")
    src = _values(src_path)
    if src.index.has_duplicates:
        raise Failed(f"{NS.SOURCES[source]} has duplicate ids")
    if not want <= set(src.index.to_numpy().tolist()):
        raise Failed(f"{NS.SOURCES[source]} does not cover all 388 noac rows")

    # ---- off the noac rows: nothing moved -----------------------------------
    g = got.to_numpy()
    rec["non_noac_vs_blend5_max_abs_diff"] = close(
        g[~noac], base.to_numpy()[~noac], 0.0,
        "the non-noac rows against the verified blend-5")
    rec["non_noac_vs_uploaded_v2_max_abs_diff"] = close(
        g[~noac], v2.to_numpy()[~noac], V2_TOL,
        f"the non-noac rows against uploaded v2 ({UPLOADED_V2})")

    # ---- on them: the pinned source -----------------------------------------
    sv = np.maximum(src.reindex(got.index[noac]).to_numpy(), B.FLOOR)
    d = close(g[noac], sv, TOL, f"the noac rows against {NS.SOURCES[source]}")
    rec.update(verifier=f"noac substitution from {NS.SOURCES[source]}, "
                        f"base pinned to {UPLOADED_V2}",
               independent=True, max_abs_diff=d,
               source_sha256=SOURCE_SHA[source], base_sha256=V2_SHA,
               noac_rms_shift=float(np.sqrt(np.mean((g[noac] - base.to_numpy()[noac]) ** 2))))
    if rec["noac_rms_shift"] == 0.0:
        raise Failed("the noac rows are identical to blend-5, so this candidate "
                     "measures nothing")


#: Names with a verifier of their own. Checked BEFORE any config, so a config
#: cannot capture one of them; see `verify`.
RESERVED = {"stack-5": lambda path, gates, rec, variant:
            verify_stack5(path, gates, rec, variant)}
RESERVED.update({f"noac-{s}": (lambda path, gates, rec, variant:
                               verify_noac_swap(path, gates, rec, variant))
                 for s in ("exp002", "drop-tailv4", "drop-v3")})


def verify(name: str, path: Path, gates: pd.DataFrame | None = None,
           variant: str = "keep-noac") -> dict:
    """Verify one candidate file. Returns the record; raises `Failed` if not."""
    rec: dict = {"name": name, "file": str(path)}
    structural(path, rec)
    gates = RT.load() if gates is None else gates
    guard_invariant(path, gates, rec)
    cfg = next((p for p in sorted(CONFIGS.glob("*.json"))
                if json.loads(p.read_text()).get("_stage_name") == name), None)
    # Reserved names are dispatched FIRST. Round 3: the config lookup came
    # first, so a config declaring `_stage_name: stack-5` would route the file
    # through `verify_blend` and skip every stack-5 pin. A config that claims a
    # reserved name is now itself an error, not a silent reroute.
    if name in RESERVED:
        if cfg is not None:
            raise Failed(f"{cfg.name} declares _stage_name {name!r}, which is reserved "
                         f"for a non-blend verifier; rename the config's _stage_name")
        RESERVED[name](path, gates, rec, variant)
    elif cfg is not None:
        verify_blend(name, path, cfg, rec)
    else:
        raise Failed(
            f"no verifier for {name!r}: it matches no config's _stage_name and is "
            f"not stack-5. A candidate that cannot be verified is not published; "
            f"add a verifier to code/verify.py before finalising it.")
    rec["verified"] = True
    return rec


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser(description="verify a candidate file")
    ap.add_argument("name")
    ap.add_argument("path", type=Path)
    a = ap.parse_args()
    try:
        print(json.dumps(verify(a.name, a.path), indent=2))
    except Failed as e:
        raise SystemExit(f"VERIFICATION FAILED: {e}")
