"""exp-063-sparseholdout: the RESULTS tables, generated from this experiment's `analysis/*.json`
only.  It reads no artifact and computes no new number; every figure it prints is already in a
record.

    .venv/bin/python experiments/exp-063-sparseholdout/code/report61.py
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import e63 as E                                                       # noqa: E402

sys.path.insert(0, str(E.ROOT / "experiments/exp-046-surfacefit/code"))
import nooverwrite as NO                                              # noqa: E402

OUT = []


def w(s=""):
    OUT.append(s)


def f4(x):
    return f"{x:+.4f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    a = ap.parse_args()
    p = E.out_path(E.ANALYSIS / "report61.md")
    NO.refuse_existing([p], False)
    oos = E.load_json(E.ANALYSIS / "oos63.json")
    bnd = E.load_json(E.ANALYSIS / "bound63.json")
    masks = {r: E.load_json(E.ANALYSIS / f"mask63-{r}.json") for r in E.ORDER}
    fits = {r: E.load_json(E.ANALYSIS / f"fit61-{r}.json") for r in E.ORDER}

    w("# exp-061 report tables (generated by `code/report61.py` from `analysis/*.json`)\n")

    w("## 1. The masks, the shams and the matched null\n")
    w("| rotation | n* | columns below | kept | excluded columns | non-zero true stand / rwy / op |")
    w("|---|---|---|---|---|---|")
    for r in E.ORDER:
        for ns in E.THRESHOLDS:
            s = masks[r]["support"][str(ns)]
            nz = s["nonzero_true"]
            w(f"| {r} | {ns} | {s['columns_below']} | {s['columns_in_kept_groups']} | "
              f"{s['excluded_columns']} | {nz['stand']} / {nz['rwy']} / {nz['op']} |")
    w("")
    w("| rotation | groups proved | group x cell identities | permutations non-identity | "
      "matched null resolved | failing cells |")
    w("|---|---|---|---|---|---|")
    for r in E.ORDER:
        i, m = masks[r]["identities"], masks[r]["matched_null"]
        w(f"| {r} | {i['groups_checked']} | {i['cells_checked']} | "
          f"{i['all_permutations_non_identity']} | {m['resolved']} | "
          f"{len(m['failing_cells'])} of {m['cells']} |")
    w("")

    w("## 2. The selection (level B, the primary level)\n")
    w("| rotation | arm | cell (n*, lambda, c) | prior columns | beta > 0 cells of 30 | mean beta |")
    w("|---|---|---|---|---|---|")
    for r in E.ORDER:
        for arm in E.ARMS:
            b = fits[r]["arms"][arm]["levels"]["B"]
            w(f"| {r} | {arm} | {b['cell']} | {b['prior_nonzero_columns']} | "
              f"{b['beta_nonzero_cells']} | {b['beta_mean']:.3f} |")
    w("")
    w("| rotation | arm | level A cell | beta > 0 of 10 | mean beta |")
    w("|---|---|---|---|---|")
    for r in E.ORDER:
        for arm in ("zero", "true", "gmean", "donor", "shuffle"):
            b = fits[r]["arms"][arm]["levels"]["A"]
            w(f"| {r} | {arm} | {b['cell']} | {b['beta_nonzero_cells'] // 3} | "
              f"{b['beta_mean']:.3f} |")
    w("")

    w("## 3. The sixteen-condition historical-reuse gate (level B)\n")
    w("| true over | jul s2/row | jan s2/row | board gain s | board 1-day | board 2-day | "
      "board 3-day | band wholly below zero | pass |")
    w("|---|---|---|---|---|---|---|---|---|")
    for c in E.GATE_CONTROLS:
        cc = oos["contrasts"][f"true_vs_{c}"]["B"]
        g = oos["gate"][c]
        w(f"| {c} | {cc['folds']['jul']['mse_gain_s2_per_row']:+.3f} | "
          f"{cc['folds']['jan']['mse_gain_s2_per_row']:+.3f} | "
          f"**{f4(g['board_gain_s'])}** | [{f4(g['board_ci_1d'][0])}, {f4(g['board_ci_1d'][1])}] | "
          f"[{f4(cc['board']['ci_block_2d'][0])}, {f4(cc['board']['ci_block_2d'][1])}] | "
          f"[{f4(cc['board']['ci_block_3d'][0])}, {f4(cc['board']['ci_block_3d'][1])}] | "
          f"{g['band_wholly_below_zero_2d_3d']} | **{g['pass']}** |")
    wa = oos["winner_adjusted"]["B"]
    w("")
    w(f"Winner-adjusted (level B): point **{f4(wa['point_s'])} s**, "
      f"1-day [{f4(wa['ci_block_1d'][0])}, {f4(wa['ci_block_1d'][1])}], "
      f"2-day [{f4(wa['ci_block_2d'][0])}, {f4(wa['ci_block_2d'][1])}], "
      f"3-day [{f4(wa['ci_block_3d'][0])}, {f4(wa['ci_block_3d'][1])}]; winning sham on the "
      f"original rows `{wa['winning_sham_on_the_original_rows']}`. "
      f"**advance = {oos['gate']['advance']}**\n")

    w("Every arm against the common base, level B:\n")
    w("| arm over base | jul s2/row | jan s2/row | dec s2/row | board gain s | board 1-day |")
    w("|---|---|---|---|---|---|")
    for arm in E.ARMS + ("sham_mean",):
        cc = oos["contrasts"][f"{arm}_vs_base"]["B"]
        w(f"| {arm} | {cc['folds']['jul']['mse_gain_s2_per_row']:+.3f} | "
          f"{cc['folds']['jan']['mse_gain_s2_per_row']:+.3f} | "
          f"{cc['folds']['dec']['mse_gain_s2_per_row']:+.3f} | "
          f"{f4(cc['board']['board_gain_s'])} | "
          f"[{f4(cc['board']['ci_block_1d'][0])}, {f4(cc['board']['ci_block_1d'][1])}] |")
    w("")
    w("dec, the calm control (zero board weight; it cannot pass or fail the gate):\n")
    w("| true over | dec s2/row | dec RMSE gain s | dec 1-day | dec 3-day |")
    w("|---|---|---|---|---|")
    for c in ("zero", "gmean", "donor", "shuffle"):
        d = oos["contrasts"][f"true_vs_{c}"]["B"]["folds"]["dec"]
        w(f"| {c} | {d['mse_gain_s2_per_row']:+.3f} | {f4(d['rmse_gain_s'])} | "
          f"[{f4(d['ci_block_1d'][0])}, {f4(d['ci_block_1d'][1])}] | "
          f"[{f4(d['ci_block_3d'][0])}, {f4(d['ci_block_3d'][1])}] |")
    w("")
    waA = oos["winner_adjusted"]["A"]
    w("Level A, descriptive (it enters no gate condition):\n")
    w("| true over | jul s2/row | jan s2/row | board gain s | board 1-day |")
    w("|---|---|---|---|---|")
    for c in ("zero", "gmean", "donor", "shuffle", "sham01"):
        cc = oos["contrasts"][f"true_vs_{c}"]["A"]
        w(f"| {c} | {cc['folds']['jul']['mse_gain_s2_per_row']:+.3f} | "
          f"{cc['folds']['jan']['mse_gain_s2_per_row']:+.3f} | "
          f"{f4(cc['board']['board_gain_s'])} | "
          f"[{f4(cc['board']['ci_block_1d'][0])}, {f4(cc['board']['ci_block_1d'][1])}] |")
    w("")
    w(f"Level-A winner-adjusted: {f4(waA['point_s'])} s, "
      f"1-day [{f4(waA['ci_block_1d'][0])}, {f4(waA['ci_block_1d'][1])}].\n")

    w("## 4. COMMON.md serving tables\n")
    w("| rotation | arm | RMSE | clean | <= 3600 | > 3600 | no-NM |")
    w("|---|---|---|---|---|---|---|")
    for r in E.ORDER:
        t = oos["tables"][r]
        for arm in ("base", "zero|B", "true|B", "gmean|B", "donor|B", "shuffle|B", "true|A"):
            x = t[arm]
            w(f"| {r} | {arm} | {x['rmse']:.4f} | {x['rmse_clean']:.4f} | {x['rmse_le3600']:.4f} | "
              f"{x['rmse_gt3600']:.1f} | {x['rmse_nonm']:.1f} |")
    w("")
    w("Board recombination (jul and jan at the ranking shares):\n")
    w("| arm | board RMSE | board clean | board <= 3600 | board > 3600 |")
    w("|---|---|---|---|---|")
    for arm in ("base", "zero|B", "true|B", "const|B", "gmean|B", "donor|B", "shuffle|B", "true|A"):
        def bb(col):
            return float(np.sqrt(sum(s * oos["tables"][r][arm][col] ** 2
                                     for r, s in E.BOARD.items())))
        w(f"| {arm} | {bb('rmse'):.4f} | {bb('rmse_clean'):.4f} | {bb('rmse_le3600'):.4f} | "
          f"{bb('rmse_gt3600'):.1f} |")
    w("")

    w("## 5. The airport-adjusted bound on V (in-sample, descriptive; it is not a test)\n")
    w("| bound kind | level | true board s | true rank of 11 | sham mean | sham max | "
      "true beats every sham | gmean | donor | shuffle |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for key, x in bnd["levels"].items():
        kind, lev = key.split("|")
        g = x["board_gain_s"]
        star = " (primary)" if key == "adjusted_all_rows|B" else ""
        w(f"| {kind} | {lev}{star} | **{f4(g['true'])}** | **{x['true_rank_of_11']}** | "
          f"{f4(x['sham_mean_s'])} | {f4(x['sham_max_s'])} | {x['true_beats_every_sham']} | "
          f"{f4(g['gmean'])} | {f4(g['donor'])} | {f4(g['shuffle'])} |")
    b = bnd["winner_adjusted_three_day_band"]
    w("")
    w(f"Winner-adjusted three-day band on the primary bound: point **{f4(b['point_s'])} s**, "
      f"band **[{f4(b['ci_block_3d'][0])}, {f4(b['ci_block_3d'][1])}]**, "
      f"{100 * b['gain_positive_share']:.1f} % of draws positive, winning sham on the original "
      f"rows `{b['winning_sham_on_the_original_rows']}`. "
      f"**bound_condition_met = {bnd['reading_inputs']['bound_condition_met']}**\n")
    w("| rotation | direct-recomputation points | max relative difference | max mixed rows | "
      "max always-clipped rows |")
    w("|---|---|---|---|---|")
    for r, x in bnd["rotations"].items():
        w(f"| {r} | {x['checks']['points']} | {x['checks']['max_relative_difference']:.2e} | "
          f"{x['clip_mixed_max']} | {x['always_clipped_max']} |")
    w("")

    p.write_text("\n".join(OUT) + "\n")
    print("\n".join(OUT))
    print(f"\nwritten {p.relative_to(E.ROOT)}")


if __name__ == "__main__":
    main()
