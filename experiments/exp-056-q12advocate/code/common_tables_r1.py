"""exp-056-q12advocate: the board table with every COMMON.md column (review round 2, finding 4).

`code/common_tables.py` wrote a compact table with the all-row RMSE of each fold and the board, which
omits the <= 3,600 s, > 3,600 s and no-NM columns. This replaces it with the board recombination of
every column: for column k and arm a, sqrt(sum over jul and jan of share(r) * RMSE_k(r, a)^2) at the
ranking shares. The per-fold tables of `analysis/common-tables.md` are unchanged. From
`analysis/iter1.json` and `iter2.json` (`tables`). Writes `analysis/common-tables-r1.md`. No label is
read.

    .venv/bin/python experiments/exp-056-q12advocate/code/common_tables_r1.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import e56 as E                                                       # noqa: E402

sys.path.insert(0, str(E.ROOT / "experiments/exp-046-surfacefit/code"))
import nooverwrite as NO                                              # noqa: E402

OUT = E.ANALYSIS / "common-tables-r1.md"
ARMS = ("base", "zero", "true", "gmean", "donor", "shuffle")
COLS = ("rmse", "rmse_clean", "rmse_le3600", "rmse_gt3600", "rmse_nonm")


def board(t: dict, arm: str, col: str) -> float:
    return float(np.sqrt(sum(s * t[r][arm][col] ** 2 for r, s in E.BOARD.items())))


def main() -> None:
    NO.refuse_existing([OUT], False)
    tabs = {it: E.load_json(E.ANALYSIS / f"iter{it}.json")["tables"] for it in (1, 2)}
    lines = ["# exp-056 board table with every COMMON.md column (generated by `code/common_tables_r1.py`)", "",
             "Board = jul (2025-07) and jan (2025-01) at the ranking shares "
             f"{E.BOARD['jul']:.4f} / {E.BOARD['jan']:.4f}, each column recombined from its fold RMSE; dec has "
             "zero board weight. Per-fold tables: `analysis/common-tables.md`.", "",
             "| iteration | arm | RMSE | clean | ≤ 3,600 | > 3,600 | no-NM |", "|---|---|---|---|---|---|---|"]
    for it in (1, 2):
        for arm in ARMS:
            if it == 2 and arm in ("base", "zero"):
                continue
            lines.append(f"| {it} | {arm} | " + " | ".join(f"{board(tabs[it], arm, c):.4f}" for c in COLS) + " |")
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"written {OUT.name}")


if __name__ == "__main__":
    main()
