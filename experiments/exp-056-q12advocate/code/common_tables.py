"""exp-056-q12advocate: the COMMON.md tables for RESULTS, every fold and column (review round 1, finding 9).

From `analysis/iter1.json` and `iter2.json` (`tables`), for every scored fold (july = 2025-07 =
`iso_jul_v`, jan = 2025-01, dec = 2025-12) and arm: ALL-ROW RMSE, clean, <= 3,600 s, > 3,600 s and
no-NM, plus the board RMSE at the ranking shares. Also the attempt lines MODES.md asks for
(iteration, mechanism, july and dec RMSE, fraction of the remaining gap closed), where the gap is
the post-hoc ceiling of `analysis/gridoracle.json`: true's best registered-beta point over zero's
registered pick. Writes `analysis/common-tables.md`. No label is read.

    .venv/bin/python experiments/exp-056-q12advocate/code/common_tables.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import e56 as E                                                       # noqa: E402

sys.path.insert(0, str(E.ROOT / "experiments/exp-046-surfacefit/code"))
import nooverwrite as NO                                              # noqa: E402

OUT = E.ANALYSIS / "common-tables.md"
ARMS = ("base", "zero", "true", "gmean", "donor", "shuffle")
FOLDS = (("jul", "july (2025-07)"), ("jan", "jan (2025-01)"), ("dec", "dec (2025-12)"))


def board(t: dict, arm: str) -> float:
    return float(np.sqrt(sum(s * t[r][arm]["rmse"] ** 2 for r, s in E.BOARD.items())))


def main() -> None:
    NO.refuse_existing([OUT], False)
    tabs = {it: E.load_json(E.ANALYSIS / f"iter{it}.json")["tables"] for it in (1, 2)}
    g = E.load_json(E.ANALYSIS / "gridoracle.json")
    ceiling = g["arms"]["true"]["best_registered_beta"]["over_zero_pick_board_s"]
    lines = ["# exp-056 COMMON.md tables (generated by `code/common_tables.py` from iter1.json and iter2.json)", "",
             "ALL-ROW on V. Iteration 2 changes only the arms with a prior; base and zero are the same in both.", ""]
    lines += ["| iteration | arm | july | dec | jan | board |", "|---|---|---|---|---|---|"]
    for it in (1, 2):
        for arm in ARMS:
            if it == 2 and arm in ("base", "zero"):
                continue
            t = tabs[it]
            lines.append(f"| {it} | {arm} | {t['jul'][arm]['rmse']:.3f} | {t['dec'][arm]['rmse']:.3f} | "
                         f"{t['jan'][arm]['rmse']:.3f} | {board(t, arm):.4f} |")
    for r, name in FOLDS:
        t1 = tabs[1][r]
        lines += ["", f"**{name}**: {t1['base']['rows']:,} rows, of which > 3,600 s {t1['base']['rows_gt3600']:,} and "
                  f"no-NM {t1['base']['rows_nonm']:,}", "",
                  "| iteration | arm | RMSE | clean | ≤ 3,600 | > 3,600 | no-NM |", "|---|---|---|---|---|---|---|"]
        for it in (1, 2):
            for arm in ARMS:
                if it == 2 and arm in ("base", "zero"):
                    continue
                x = tabs[it][r][arm]
                lines.append(f"| {it} | {arm} | {x['rmse']:.3f} | {x['rmse_clean']:.3f} | {x['rmse_le3600']:.3f} | "
                             f"{x['rmse_gt3600']:.3f} | {x['rmse_nonm']:.3f} |")
    lines += ["", f"Attempt lines (MODES.md). Gap = post-hoc ceiling of the registered family for true over zero's "
              f"registered pick, board {ceiling:+.4f} s (`analysis/gridoracle.json`; "
              f"{g['zero_lam_oracle_over_zero_pick']['board_s']:+.4f} s of it is zero's lambda alone).", ""]
    b0 = board(tabs[1], "zero")
    for it, what in ((0, "reduced base, no correction"), (1, "cross-month key correction on S with the taxi-in "
                                                             "prior as its shrinkage target (lam, beta on S<->I)"),
                     (2, "the same with the prior weighted by c/(c + n_A), c chosen with lam and beta")):
        arm = "base" if it == 0 else "true"
        t = tabs[max(it, 1)]
        gain = b0 - board(t, arm)
        frac = "n/a (below the correction baseline zero)" if it == 0 else f"{gain / ceiling:+.1%}"
        lines.append(f"- attempt {it}: {what}; july {t['jul'][arm]['rmse']:.3f}, dec {t['dec'][arm]['rmse']:.3f}, "
                     f"jan {t['jan'][arm]['rmse']:.3f}, board {board(t, arm):.4f}; over zero {gain:+.4f} s; "
                     f"fraction of the remaining gap closed {frac}")
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines[-3:]))
    print(f"written {OUT.name}")


if __name__ == "__main__":
    main()
