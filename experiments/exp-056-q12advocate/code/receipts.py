"""exp-056-q12advocate: the committed manifest of every private Kaggle output this replay uses.

Reads each pulled `artifacts/exp-056/kaggle/port-<member>-<group>.json`, re-hashes every
prediction file it names, checks the kernel's logged data hashes against `data/raw`, and writes
`analysis/kernel-receipts.json` and `analysis/kernel-receipts.md`: slug, git commit of the code
dataset, per fold rows, file SHA-256, ids-then-predictions vector SHA-256, wall time, peak host
and GPU memory, and GPU-hours. The prediction files stay git-ignored; this manifest and the
private kernel slugs are their durable address. Label-free.

    .venv/bin/python experiments/exp-056-q12advocate/code/receipts.py
"""
from __future__ import annotations

import os

import argparse
import json
import sys
from pathlib import Path


def kaggle_user() -> str:
    """Read the account only when a Kaggle route is needed."""
    user = os.environ.get("PRC_KAGGLE_USER", "").strip()
    if not user:
        raise RuntimeError("Set PRC_KAGGLE_USER to your Kaggle account before using a Kaggle route")
    return user

sys.path.insert(0, str(Path(__file__).resolve().parent))
import e56 as E                                                       # noqa: E402

sys.path.insert(0, str(E.ROOT / "experiments/exp-046-surfacefit/code"))
import nooverwrite as NO                                              # noqa: E402

OUT_J = E.ANALYSIS / "kernel-receipts.json"
OUT_M = E.ANALYSIS / "kernel-receipts.md"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--overwrite", action="store_true")
    a = ap.parse_args()
    NO.refuse_existing([OUT_J, OUT_M], a.overwrite)
    raw = {p.name: E.sha_file(p) for p in sorted((E.ROOT / "data/raw").glob("*.parquet"))}
    rec, rows_md, gpu_h = {}, [], 0.0
    for port_p in sorted(E.KAGGLE.glob("port-*.json")):
        member, group = port_p.stem[len("port-"):].rsplit("-", 1)
        p = json.loads(port_p.read_text())
        data_ok = all(raw.get(k) == v for k, v in p["data_sha256"].items() if k.endswith(".parquet")
                      and k in raw)
        folds = {}
        for fold, w in p["written"].items():
            f = E.KAGGLE / f"{member}--{fold}.parquet"
            sha = E.sha_file(f)
            if sha != w["file_sha256"]:
                raise SystemExit(f"{f.name}: {sha[:16]} is not the kernel's {w['file_sha256'][:16]}")
            folds[fold] = {"rows": w["rows"], "file": str(f.relative_to(E.ROOT)), "file_sha256": sha,
                           "vector_sha256_ids_then_pred": w["vector_sha256_ids_then_pred"]}
        wall = sum(s["wall_s"] for s in p["steps"]) / 3600
        if "none" not in str(p["gpu"]).lower():
            gpu_h += wall
        slug = f"{kaggle_user()}/prc-iso-{member.lower()}-{group}"
        rec[f"{member}-{group}"] = {"slug": slug, "git": p["git"][0], "gpu": p["gpu"],
                                    "data_sha256_match_mac": data_ok, "wall_h": round(wall, 3),
                                    "peak_host_used_gb": p["peak_host_used_gb"],
                                    "peak_gpu_mib": p["peak_gpu_mib"], "steps": p["steps"],
                                    "thin": p.get("thin"), "folds": folds}
        for fold, x in folds.items():
            rows_md.append(f"| `{slug}` | {fold} | {x['rows']:,} | `{x['file_sha256'][:16]}…` | "
                           f"`{x['vector_sha256_ids_then_pred'][:16]}…` |")
    summ = ["| kernel | code git | data = Mac | wall, h | peak host, GB | peak GPU, MiB |",
            "|---|---|---|---|---|---|"]
    for k, x in rec.items():
        summ.append(f"| `{x['slug']}` | `{x['git'][:12]}` | {x['data_sha256_match_mac']} | {x['wall_h']:.2f} | "
                    f"{x['peak_host_used_gb']} | {x['peak_gpu_mib']} |")
    md = ["<!-- generated by code/receipts.py -->", "", *summ, "",
          f"GPU wall time, all GPU kernels: **{gpu_h:.2f} h**.", "",
          "| kernel | fold | rows | file sha256 | ids-then-pred sha256 |", "|---|---|---|---|---|", *rows_md, ""]
    NO.refuse_existing([OUT_J, OUT_M], a.overwrite)
    OUT_J.write_text(json.dumps({"what": __doc__.strip().splitlines()[0], "utc": E.utc(),
                                 "gpu_wall_h": round(gpu_h, 3), "kernels": rec}, indent=1, sort_keys=True))
    OUT_M.write_text("\n".join(md))
    print(f"{len(rec)} kernels, {sum(len(x['folds']) for x in rec.values())} files, GPU {gpu_h:.2f} h")


if __name__ == "__main__":
    main()
