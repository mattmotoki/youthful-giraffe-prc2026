"""exp-056-q12advocate: the RESULTS tables of one priced iteration, generated from its records only.

Reads `analysis/iter<N>.json` (or any priced record given by path) and writes the markdown tables
RESULTS.md quotes: the gate, every registered contrast with its 1-, 2- and 3-day intervals, the
picks, the COMMON.md tables, the sham seeds, the training-size and time-origin controls, the
residual-alignment and support diagnostics, and the secondary sparse-stand read. No number in
RESULTS.md is typed by hand.

    .venv/bin/python experiments/exp-056-q12advocate/code/report.py analysis/iter1.json
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import e56 as E                                                       # noqa: E402

sys.path.insert(0, str(E.ROOT / "experiments/exp-046-surfacefit/code"))
import nooverwrite as NO                                              # noqa: E402

CONTROLS = ("zero", "shuffle", "gmean", "donor", "sham")


def ci(x, nd=4):
    return f"[{x[0]:+.{nd}f}, {x[1]:+.{nd}f}]"


def contrast_rows(name: str, cc: dict) -> list:
    """One row per fold and one for the board: point, RMSE gain, 1/2/3-day intervals."""
    rows = []
    for r in E.ORDER:
        f = cc["folds"][r]
        rows.append(f"| {name} | {r} | {f['mse_gain_s2_per_row']:+.2f} | {f['rmse_gain_s']:+.4f} | "
                    f"{ci(f['ci_block_1d'], 2)} | {ci(f['ci_block_2d'], 2)} | {ci(f['ci_block_3d'], 2)} |")
    b = cc["board"]
    rows.append(f"| {name} | **board** | – | **{b['board_gain_s']:+.4f}** | {ci(b['ci_block_1d'])} | "
                f"{ci(b['ci_block_2d'])} | {ci(b['ci_block_3d'])} |")
    return rows


HEAD = ["| contrast (B over A) | fold | mean gain, s²/row | RMSE gain, s | 1-day | 2-day | 3-day |",
        "|---|---|---|---|---|---|---|"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("record", help="a priced record, relative to the experiment directory")
    ap.add_argument("--overwrite", action="store_true")
    a = ap.parse_args()
    src = E.EXP / a.record
    d = json.loads(src.read_text())
    out = src.with_name("report-" + src.stem + ".md")
    NO.refuse_existing([out], a.overwrite)
    it = d.get("iteration", 1)
    L = [f"<!-- generated by code/report.py from {a.record} (sha256 {E.sha_file(src)}) -->", ""]

    g = d["gate"]
    L += [f"### Gate (SPEC §3.8): advance = **{g['advance']}**", "",
          "| true over | jul point > 0 | jan point > 0 | board gain, s | board 1-day | resolved 2/3-day reversal | pass |",
          "|---|---|---|---|---|---|---|"]
    for c in CONTROLS:
        x = g[c]
        L.append(f"| {c} | {x['fold_points_positive']['jul']} | {x['fold_points_positive']['jan']} | "
                 f"{x['board_gain_s']:+.4f} | {ci(x['board_ci_1d'])} | {x['resolved_reversal_2d_3d']} | "
                 f"**{x['pass']}** |")
    L += ["", "### Registered contrasts, main design", ""] + HEAD
    for c in CONTROLS:
        L += contrast_rows(f"true over {c}", d["contrasts"][f"true_vs_{c}"]["main"])
    for arm in ("zero", "true", "gmean", "donor", "shuffle", "sham"):
        L += contrast_rows(f"{arm} over base", d["contrasts"][f"{arm}_vs_base"]["main"])
    if it == 2:
        L += contrast_rows("iteration-2 true over iteration-1 true",
                           d["contrasts"]["true_it2_vs_true_it1"]["main"])

    L += ["", "### Picks (inner selection on S ↔ I; V not read)", "",
          "| arm | " + " | ".join(E.ORDER) + " |", "|---|" + "---|" * len(E.ORDER)]
    for arm in d["picks"]["jul"]:
        cells = []
        for r in E.ORDER:
            pk = d["picks"][r][arm]
            cells.append(f"λ {pk['lam']}, β {pk['beta']}" + (f", c {pk['c']}" if pk.get("c") else ""))
        L.append(f"| {arm} | " + " | ".join(cells) + " |")

    L += ["", "### COMMON.md tables (V, ALL-ROW; clean drops the fold's unreached-rollover rows)", "",
          "| rotation | arm | RMSE | clean | ≤ 3,600 | > 3,600 | no-NM | rows |", "|---|---|---|---|---|---|---|---|"]
    for r in E.ORDER:
        for arm, t in d["tables"][r].items():
            L.append(f"| {r} | {arm} | {t['rmse']:.4f} | {t['rmse_clean']:.4f} | {t['rmse_le3600']:.4f} | "
                     f"{t['rmse_gt3600']:.2f} | {t['rmse_nonm']:.2f} | {t['rows']:,} |")

    L += ["", "### Sham seeds (true over each permuted-prior sham, main design)", "",
          "| seed | board gain, s | 1-day | 3-day |", "|---|---|---|---|"]
    for s, b in d["sham_seeds"].items():
        L.append(f"| {s} | {b['board_gain_s']:+.4f} | {ci(b['ci_block_1d'])} | {ci(b['ci_block_3d'])} |")

    L += ["", "### Training-size and time-origin controls", ""] + HEAD
    for arm in ("zero", "true"):
        L += contrast_rows(f"{arm}: exposed over matched isolated", d["contrasts"][f"{arm}_expo_vs_expo_ref"])
        L += contrast_rows(f"{arm}: fit on S over fit on I", d["contrasts"][f"{arm}_originS_vs_originI"])
    for dsg in ("expo", "expo_ref", "originS", "originI"):
        L += contrast_rows(f"true over zero ({dsg})", d["contrasts"]["true_vs_zero"][dsg])

    L += ["", "### Residual alignment of the unit true prior (Σeq / Σq², e = V residual of zero)", "",
          "| rotation | all P | corr | stand | runway | operator | inner (I, fit on S) |", "|---|---|---|---|---|---|---|"]
    for r in E.ORDER:
        x = d["diagnostics"][r]
        fam = x["alignment_by_family"]
        inner = d["inner_alignment_on_I"][r]

        def fmt(v):
            return "–" if v is None else f"{v:+.4f}"
        L.append(f"| {r} | {fmt(x['alignment_all']['alignment'])} | {fmt(x['alignment_all']['corr'])} | "
                 f"{fmt(fam['stand']['alignment'])} | {fmt(fam['rwy']['alignment'])} | "
                 f"{fmt(fam['op']['alignment'])} | {fmt(inner['alignment'])} |")
    L += ["", "### Support strata (true over zero SSE gain, 10⁶ s², and alignment)", "",
          "| rotation | stratum | rows | SSE gain | alignment |", "|---|---|---|---|---|"]
    for r in E.ORDER:
        for grp in ("by_nA_stand", "by_nS_stand"):
            for name, x in d["diagnostics"][r][grp].items():
                al = "–" if x["alignment"] is None else f"{x['alignment']:+.4f}"
                L.append(f"| {r} | {name} | {x['rows']:,} | {x['true_vs_zero_sse_gain_Ms2']:+.3f} | {al} |")

    sec = d["secondary_sparse_stand"]
    L += ["", f"### Secondary read, not the gate: {sec['stratum']} (rows {sec['rows']})", "",
          f"exp-054 route (true over shuffle, 1-day above zero on both board folds): "
          f"**{sec['exp054_route_true_beats_shuffle_1d_above_zero_both_board_folds']}**", ""] + HEAD
    for c in CONTROLS:
        cc = sec[f"true_vs_{c}"]
        for r in E.ORDER:
            f = cc["folds"][r]
            L.append(f"| true over {c} | {r} | {f['mse_gain_s2_per_row']:+.2f} | {f['rmse_gain_s']:+.4f} | "
                     f"{ci(f['ci_block_1d'], 2)} | {ci(f['ci_block_2d'], 2)} | {ci(f['ci_block_3d'], 2)} |")
        b = cc["board"]
        L.append(f"| true over {c} | **board** | – | **{b['board_gain_s']:+.4f}** | {ci(b['ci_block_1d'])} | "
                 f"{ci(b['ci_block_2d'])} | {ci(b['ci_block_3d'])} |")

    L += ["", f"Label reads: " + "; ".join(f"{x['month']} at {x['utc']} ({x['why']})" for x in d["label_reads"])
          if d["label_reads"] else "Label reads: none (dry)",
          f"Row losses: `{d['artifacts']['rows']['path']}` sha256 `{d['artifacts']['rows']['sha256']}`; "
          f"draws `{d['artifacts']['draws']['path']}` sha256 `{d['artifacts']['draws']['sha256']}`.", ""]
    NO.refuse_existing([out], a.overwrite)
    out.write_text("\n".join(L))
    print(f"written {out.relative_to(E.ROOT)} ({len(L)} lines)")


if __name__ == "__main__":
    main()
