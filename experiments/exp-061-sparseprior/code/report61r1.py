"""exp-061-sparseprior: the round-1 review answer to finding 8 --- the FULL serving report.

`code/report61.py` printed seven of the thirty-five arm-and-level rows each fold carries, so
RESULTS section 4 could not cite it for the complete table.  This job writes every row
`analysis/oos61.json` holds: all seventeen arms at both levels, per fold and recombined on the
board, with the four COMMON.md columns, and every contrast against the base and against `true`.
It reads this experiment's records only and computes no new number.

    .venv/bin/python experiments/exp-061-sparseprior/code/report61r1.py
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import e61 as E                                                       # noqa: E402

sys.path.insert(0, str(E.ROOT / "experiments/exp-046-surfacefit/code"))
import nooverwrite as NO                                              # noqa: E402

OUT = []


def w(s=""):
    OUT.append(s)


def f4(x):
    return f"{x:+.4f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--overwrite", action="store_true")
    a = ap.parse_args()
    p = E.out_path(E.ANALYSIS / "report61-r1.md")
    NO.refuse_existing([p], a.overwrite)
    oos = E.load_json(E.ANALYSIS / "oos61.json")
    rows = sorted(oos["tables"]["jul"])
    w("# exp-061 full serving report (generated by `code/report61r1.py` from `analysis/oos61.json`)\n")
    w(f"Every arm and level each fold carries: {len(rows)} rows per fold.\n")

    for r in E.ORDER:
        t = oos["tables"][r]
        w(f"## {r} ({oos['months'][r]['V'] if 'months' in oos else ''})\n")
        w("| arm | RMSE | clean | <= 3600 | > 3600 | no-NM |")
        w("|---|---|---|---|---|---|")
        for arm in rows:
            x = t[arm]
            w(f"| {arm} | {x['rmse']:.4f} | {x['rmse_clean']:.4f} | {x['rmse_le3600']:.4f} | "
              f"{x['rmse_gt3600']:.1f} | {x['rmse_nonm']:.1f} |")
        w("")

    w("## Board recombination (jul and jan at the ranking shares; dec carries no board weight)\n")
    w("| arm | board RMSE | board clean | board <= 3600 | board > 3600 |")
    w("|---|---|---|---|---|")
    for arm in rows:
        def bb(col, arm=arm):
            return float(np.sqrt(sum(s * oos["tables"][rr][arm][col] ** 2
                                     for rr, s in E.BOARD.items())))
        w(f"| {arm} | {bb('rmse'):.4f} | {bb('rmse_clean'):.4f} | {bb('rmse_le3600'):.4f} | "
          f"{bb('rmse_gt3600'):.1f} |")
    w("")

    w("## Every recorded contrast\n")
    w("| contrast | level | jul s2/row | jan s2/row | dec s2/row | board gain s | board 1-day | "
      "board 2-day | board 3-day |")
    w("|---|---|---|---|---|---|---|---|---|")
    for name in sorted(oos["contrasts"]):
        for lev in ("B", "A"):
            cc = oos["contrasts"][name].get(lev)
            if not cc:
                continue
            b = cc["board"]
            w(f"| {name} | {lev} | " + " | ".join(
                f"{cc['folds'][rr]['mse_gain_s2_per_row']:+.3f}" for rr in E.ORDER)
              + f" | {f4(b['board_gain_s'])} | "
              + " | ".join(f"[{f4(b[f'ci_block_{L}d'][0])}, {f4(b[f'ci_block_{L}d'][1])}]"
                           for L in E.BLOCK_LENGTHS) + " |")
    w("")
    p.write_text("\n".join(OUT) + "\n")
    print(f"written {p.relative_to(E.ROOT)}: {len(rows)} arm rows per fold, "
          f"{len(oos['contrasts'])} contrasts")


if __name__ == "__main__":
    main()
