"""exp-047-queue: `climb.log`, one line per attempt, generated from `analysis/*.json`.

`assignments/COMMON.md` asks for "one line per attempt: iteration, mechanism changed,
july RMSE, december RMSE, fraction of the remaining gap closed".  This lane's attempts
are corrections of v11 rather than model fits, so the two RMSE columns are v11 + h on
the rows the attempt was measured on, and the last column is the fraction of the gap to
the leader that the attempt's `2A - B` would close if it held over the whole file:
exp-041's budget is 1,182 s² of MSE for the 2.1154 s gap, so the fraction is
`2A - B / 1182`.  It is an upper bound and the report says so; nothing here is a board
number.

    OMP_NUM_THREADS=1 .venv/bin/python experiments/exp-047-queue/code/climb.py
"""
from __future__ import annotations

import json
from pathlib import Path

EXP = Path(__file__).resolve().parents[1]
AN = EXP / "analysis"
GAP_S2 = 1182.0            # exp-041 §7: the MSE that closes the 2.1154 s gap

#: file -> (iteration, mechanism, the arms to log, the population column)
ATTEMPTS = [
    ("explain-july_loo.json", "1", "F: the file's clocks, ten airports, both anchors",
     ["Fto", "Fob", "F"]),
    ("explain-december.json", "1", "F: the same, december", ["Fto", "Fob", "F"]),
    ("explain-january.json", "1", "F: the same, january", ["Fto", "Fob", "F"]),
    ("explain-july_loo-placebo.json", "1p", "F with every source event shifted +2 h",
     ["Fto", "Fob", "F"]),
    ("explain-july_loo-ehamweek-split.json", "3s",
     "N read on the split half: the neighbourhood built from the OTHER half's clocks, "
     "pairs inside (cell, half)", ["Nf", "No", "N", "own", "own_No"]),
    ("explain-july_loo-ehamweek-ridge.json", "2",
     "O/H: the observed clocks, EHAM week", ["Oob", "Hob"]),
    ("explain-july_loo-ehamweek-own.json", "3",
     "N: the neighbours' clock, and the row's own beside it",
     ["Nf", "No", "N", "own", "own_No", "own_No_Hob"]),
    ("explain-july_loo-ehamweek-permuted.json", "3p",
     "N with the observed clocks dealt out to other aircraft", ["Nf", "No", "N"]),
    ("explain-july_loo-ehamweek-byreach.json", "4",
     "N and own, one head fitted per reach class", ["own", "No", "own_No", "own_No_Hob"]),
] + [(f"explain-july_loo-thin{t}.json", "5",
      f"N with EHAM's clocks thinned to {t}", ["No", "own", "own_No"])
     for t in ("0.16", "0.30", "0.50", "0.70", "0.90")]

HEAD = ("| it | mechanism | arm | rows | july RMSE v11 → +h | december | "
        "2A − B (s²) | share of the shared component | fraction of the 1,182 s² gap |")
SEP = "|---|---|---|---:|---|---|---:|---:|---:|"


def main() -> None:
    out = ["# exp-047-queue climb log",
           "",
           "Generated by `code/climb.py` from `analysis/*.json`; not typed. The last",
           "column is `2A − B / 1182`, the fraction of the gap to the leader the",
           "attempt would close IF it held over the whole file at this amplitude — an",
           "upper bound on a within-month cross fit, never a board number.",
           "", HEAD, SEP]
    for name, it, mech, arms in ATTEMPTS:
        p = AN / name
        if not p.exists():
            continue
        d = json.loads(p.read_text())
        fold = d.get("fold", "?")
        for arm in arms:
            a = d["arms"].get(arm)
            if not a:
                continue
            r0 = a.get("rmse_v11", {}) or {}
            r1 = a.get("rmse_v11_plus_h", {}) or {}
            jul = (f"{r0.get('all')} → {r1.get('all')}"
                   if fold == "july_loo" and r0.get("all") else "–")
            dec = (f"{r0.get('all')} → {r1.get('all')}"
                   if fold == "december" and r0.get("all") else "–")
            g = a["contract"]["mse_gain_s2"]
            sh = a["all"]["share"]
            shs = "–" if sh is None else f"{100 * sh:.1f} %"
            out.append(f"| {it} | {mech} | {arm} | {a['all']['rows']:,} | {jul} | "
                       f"{dec} | {g:+.1f} | {shs} | {g / GAP_S2:+.3f} |")
    (EXP / "climb.log").write_text("\n".join(out) + "\n")
    print("wrote", EXP / "climb.log", len(out) - 6, "attempt rows")


if __name__ == "__main__":
    main()
